---@class OptionsCfg
---
--- Enables subtle matchparen “blink” of matching pairs.
--- Changes:
---   * Sets `vim.opt.showmatch` accordingly.
---   * Uses `matchtime_tenths` for blink duration.
--- Side-effects: tiny focus cue when moving over brackets; can be disabled if distracting.
---@field enable_matchparen boolean
---
--- Blink duration for the matchparen feature in tenths of a second.
--- Changes:
---   * Applied to `vim.opt.matchtime`; e.g., `2` ≙ ~200ms.
--- Side-effects: longer values increase visibility but may feel intrusive.
---@field matchtime_tenths integer

